class Ops:
    """Everything that touches the outside world. Tests replace this."""

    def __init__(self, ssh_user, ssh_key):
        self.ssh_user = ssh_user
        self.ssh_key = ssh_key

    def ssh(self, address, command, timeout=30):
        argv = [
            "ssh", "-i", self.ssh_key,
            "-o", "BatchMode=yes",
            "-o", "StrictHostKeyChecking=no",
            "-o", "UserKnownHostsFile=/dev/null",
            "-o", f"ConnectTimeout={min(timeout, 15)}",
            "-o", "LogLevel=ERROR",
            f"{self.ssh_user}@{address}", command,
        ]
        return self._run(argv, timeout)

    def local(self, argv, timeout=60):
        return self._run(argv, timeout)

    @staticmethod
    def _run(argv, timeout):
        try:
            p = subprocess.run(argv, stdin=subprocess.DEVNULL, capture_output=True,
                               text=True, timeout=timeout)
            return p.returncode == 0, (p.stdout + p.stderr).strip()
        except subprocess.TimeoutExpired:
            return False, f"(timed out after {timeout}s)"
        except OSError as e:
            return False, f"({e})"

    def http(self, method, url, data=None, headers=None, timeout=10):
        """Returns (status, parsed-json-or-text). Status 0 = no connection."""
        body = json.dumps(data).encode() if data is not None else None
        req = urllib.request.Request(url, data=body, method=method)
        for k, v in (headers or {}).items():
            req.add_header(k, v)
        if body is not None:
            req.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return resp.status, _maybe_json(resp.read())
        except urllib.error.HTTPError as e:
            return e.code, _maybe_json(e.read())
        except (urllib.error.URLError, OSError, ValueError) as e:
            return 0, str(e)

    @staticmethod
    def tcp_open(host, port, timeout=3):
        try:
            with socket.create_connection((host, port), timeout=timeout):
                return True
        except OSError:
            return False

    @staticmethod
    def resolves(name):
        try:
            socket.getaddrinfo(name, None)
            return True
        except OSError:
            return False

    @staticmethod
    def send_wol(mac, broadcast):
        payload = b"\xff" * 6 + bytes.fromhex(mac.replace(":", "")) * 16
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
            s.sendto(payload, (broadcast, 9))

    @staticmethod
    def now():
        return time.time()

    @staticmethod
    def sleep(seconds):
        time.sleep(seconds)


def _maybe_json(raw):
    raw = raw.decode(errors="replace") if isinstance(raw, bytes) else raw
    try:
        return json.loads(raw) if raw else None
    except ValueError:
        return raw


