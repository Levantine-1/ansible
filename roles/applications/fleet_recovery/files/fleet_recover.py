_RECOVERED_RE = re.compile(r"Recovered position:?\s*([0-9a-fA-F-]{36}):(-?\d+)")


def parse_position(output):
    """(uuid, seqno) from --wsrep-recover log + grastate.dat output, or None.

    The recovered position wins; grastate's seqno only counts when it is
    real (>= 0, i.e. the node shut down cleanly), and then the higher wins.
    """
    uuid, seqno = None, None
    m = _RECOVERED_RE.search(output or "")
    if m:
        uuid, seqno = m.group(1).lower(), int(m.group(2))
    g_uuid = re.search(r"^uuid:\s*([0-9a-fA-F-]{36})", output or "", re.M)
    g_seq = re.search(r"^seqno:\s*(-?\d+)", output or "", re.M)
    if g_uuid and g_seq and int(g_seq.group(1)) >= 0:
        gu, gs = g_uuid.group(1).lower(), int(g_seq.group(1))
        if uuid is None or (gu == uuid and gs > seqno):
            uuid, seqno = gu, gs
    if uuid is None or seqno is None or seqno < 0:
        return None
    return uuid, seqno


def choose_bootstrap(positions, preferred=None):
    """Pick the node to bootstrap from. positions: {node: (uuid, seqno)|None}.

    Majority cluster UUID first (a stray node from some other history must
    not win on seqno alone), then highest seqno, then the inventory's
    bootstrap=yes node, then name order. Returns (node, reason) or (None, why).
    """
    valid = {n: p for n, p in positions.items() if p}
    if not valid:
        return None, "no node reported a recoverable position"
    counts = {}
    for uuid, _ in valid.values():
        counts[uuid] = counts.get(uuid, 0) + 1
    top = max(counts.values())
    uuids = [u for u, c in counts.items() if c == top]
    if len(uuids) > 1 and preferred in valid and valid[preferred][0] in uuids:
        uuids = [valid[preferred][0]]
    elif len(uuids) > 1:
        uuids = [max(uuids, key=lambda u: max(s for uu, s in valid.values() if uu == u))]
    uuid = uuids[0]
    cands = {n: s for n, (u, s) in valid.items() if u == uuid}
    best = max(cands.values())
    tied = sorted(n for n, s in cands.items() if s == best)
    node = preferred if preferred in tied else tied[0]
    shown = ", ".join(f"{n}={p[0][:8]}:{p[1]}" if p else f"{n}=?" for n, p in sorted(positions.items()))
    return node, f"highest seqno {best} on cluster {uuid[:8]} (positions: {shown})"


def galera_assess(states):
    """Classify the cluster from per-node unit states.

    states: {node: {"reachable": bool, "mysql": str, "bootstrap": str}}
    where mysql/bootstrap are `systemctl is-active` words. Returns one of
    "starting" (a unit is mid-start -- an SST can take minutes, leave it),
    "primary" (some node is up: PXC's unit only reaches active after
    joining a primary component), or "down".
    """
    reach = {n: s for n, s in states.items() if s.get("reachable")}
    if any("activating" in (s["mysql"], s["bootstrap"]) for s in reach.values()):
        return "starting"
    if any("active" in (s["mysql"], s["bootstrap"]) for s in reach.values()):
        return "primary"
    return "down"


def _up(s):
    return s.get("reachable") and "active" in (s.get("mysql"), s.get("bootstrap"))


