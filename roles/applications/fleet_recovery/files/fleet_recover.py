# The recovery run
# --------------------------------------------------------------------------
class Recovery:
    def __init__(self, cfg, ops, state_path, dry_run=False, only=None, once=False, log=print):
        self.cfg = cfg
        self.ops = ops
        self.state_path = state_path
        self.dry_run = dry_run
        self.only = only
        self.once = once
        self.log = log
        self.state = self._load_state()
        self.planned = []        # dry-run: what would have been done
        self.notes = []          # this pass: problems/progress for the ticket

    # ---- state -----------------------------------------------------------
    def _load_state(self):
        try:
            with open(self.state_path) as f:
                return json.load(f)
        except (OSError, ValueError):
            return {}

    def _save_state(self):
        if self.dry_run or self.only:
            return
        os.makedirs(os.path.dirname(self.state_path), exist_ok=True)
        tmp = self.state_path + ".tmp"
        with open(tmp, "w") as f:
            json.dump(self.state, f, indent=1, sort_keys=True)
        os.replace(tmp, self.state_path)

    def _event(self, msg):
        self.log(msg)
        if not self.dry_run:
            self.state.setdefault("timeline", []).append([self.ops.now(), msg])

    def act(self, description, fn):
        """Perform (or, in dry-run, just record) one action."""
        if self.dry_run:
            self.planned.append(description)
            self.log(f"[dry-run] would: {description}")
            return True, "(dry-run)"
        self._event(f"ACTION: {description}")
        ok, out = fn()
        if not ok:
            self._event(f"  failed: {out[-300:]}")
        return ok, out

    def note(self, msg):
        self.notes.append(msg)
        self.log(msg)

    def since(self, key):
        """Seconds since state[key] was first set (setting it now if unset)."""
        now = self.ops.now()
        if key not in self.state:
            self.state[key] = now
        return now - self.state[key]

    # ---- phase 0 ---------------------------------------------------------
    def phase_preconditions(self):
        if not self.ops.resolves(self.cfg["dns_probe_name"]):
            self.note(f"Internal DNS isn't answering yet ({self.cfg['dns_probe_name']}); waiting for OPNsense/pi-hole.")
            return WAIT
        iface, want = self.cfg.get("lan_iface"), self.cfg.get("lan_ip")
        if iface and want:
            ok, out = self.ops.local(["ip", "-4", "-o", "addr", "show", "dev", iface])
            if ok and f" {want}/" not in out:
                if not self.state.get("lan_ip_reconfigured"):
                    self.act(f"re-request {iface}'s DHCP lease (expected {want})",
                             lambda: self.ops.local(["networkctl", "reconfigure", iface]))
                    self.state["lan_ip_reconfigured"] = True
                    return PROGRESS
                self.note(f"`service`'s {iface} doesn't have {want} (has: {out.split()[3:4]}); "
                          "the home-LAN entrances (dashboard, Vault UI, livecam-lan) are unreachable. "
                          "Check the DD-WRT static lease.")
                return PROBLEM
        return OK

    # ---- phase 1 ---------------------------------------------------------
    HV_CMD = (
        "cut -d' ' -f1 /proc/uptime; "
        "for id in $(sudo qm list | awk 'NR>1 && $3==\"stopped\" {print $1}'); do "
        "echo \"STOPPED $id onboot=$(sudo qm config $id | sed -n 's/^onboot: //p')"
        " template=$(sudo qm config $id | sed -n 's/^template: //p')\"; done"
    )

    def phase_hypervisors(self):
        result = OK
        lo, hi = self.cfg.get("vm_start_window", [600, 3600])
        for hv in self.cfg["hypervisors"]:
            name = hv["name"]
            ok, out = self.ops.ssh(hv["address"], self.HV_CMD, timeout=30)
            if not ok:
                down_for = self.since(f"hv_down_since:{name}")
                last_wol = self.state.get(f"wol_sent:{name}", 0)
                if hv.get("mac") and down_for > 120 and self.ops.now() - last_wol > 300:
                    self.act(f"send Wake-on-LAN to {name} ({hv['mac']})",
                             lambda hv=hv: (self.ops.send_wol(hv["mac"], self.cfg["wol_broadcast"]) or True, ""))
                    if not self.dry_run:
                        self.state[f"wol_sent:{name}"] = self.ops.now()
                self.note(f"Hypervisor {name} ({hv['address']}) isn't answering (for {int(down_for // 60)} min). "
                          "If Wake-on-LAN doesn't bring it back, it needs its power button -- and check "
                          "its BIOS 'Restore on AC power loss' setting.")
                result = PROBLEM
                continue
            self.state.pop(f"hv_down_since:{name}", None)
            lines = out.splitlines()
            try:
                uptime = float(lines[0])
            except (IndexError, ValueError):
                self.note(f"Couldn't read {name}'s uptime: {out[:200]}")
                result = PROBLEM
                continue
            for line in lines[1:]:
                m = re.match(r"STOPPED (\d+) onboot=(\S*) template=(\S*)", line)
                if not m or m.group(2) != "1" or m.group(3) == "1":
                    continue
                vmid = m.group(1)
                if uptime < lo:
                    # Proxmox's own ordered start-all may still be working
                    # through its list -- starting VMs now would undo the
                    # startup order it exists to enforce.
                    self.note(f"VM {vmid} on {name} not started yet; Proxmox is still in its boot ordering.")
                    result = WAIT if result == OK else result
                elif uptime <= hi:
                    self.act(f"start VM {vmid} on {name} (onboot=1, still stopped {int(uptime // 60)} min after host boot)",
                             lambda hv=hv, vmid=vmid: self.ops.ssh(hv["address"], f"sudo qm start {vmid}", timeout=120))
                    result = PROGRESS if result in (OK, WAIT) else result
                else:
                    # Host has been up for a while: a stopped onboot VM is a
                    # deliberate stop, not a failed boot. Leave it alone.
                    self.log(f"VM {vmid} on {name} is stopped but {name} has been up "
                             f"{int(uptime // 3600)}h -- assuming that's deliberate.")
        return result

    # ---- phase 2 ---------------------------------------------------------
    def phase_nginx(self):
        ok, out = self.ops.local(["systemctl", "is-active", "nginx"])
        state = out.strip().splitlines()[-1] if out.strip() else ""
        if state in ("active", "activating", "reloading"):
            return OK
        self.act("restart nginx on service", lambda: self.ops.local(["systemctl", "restart", "nginx"], timeout=600))
        return PROGRESS

    # ---- phase 3 ---------------------------------------------------------
    GALERA_STATE_CMD = (
        "printf 'mysql=%s bootstrap=%s mysqld=%s\\n' \"$(systemctl is-active mysql)\" "
        "\"$(systemctl is-active mysql@bootstrap)\" "
        "\"$(pgrep -x mysqld >/dev/null && echo yes || echo no)\""
    )
    RECOVER_CMD = (
        "sudo rm -f /tmp/wsrep_recover.log; "
        "sudo mysqld --wsrep-recover --user=mysql --log-error=/tmp/wsrep_recover.log >/dev/null 2>&1; "
        "sudo grep -a 'Recovered position' /tmp/wsrep_recover.log | tail -n 1; "
        "sudo grep -E '^(uuid|seqno):' /var/lib/mysql/grastate.dat"
    )

    def galera_states(self):
        states = {}
        for node in self.cfg["galera_nodes"]:
            ok, out = self.ops.ssh(node["address"], self.GALERA_STATE_CMD, timeout=20)
            m = re.search(r"mysql=(\S+) bootstrap=(\S+) mysqld=(\S+)", out or "")
            if not ok or not m:
                states[node["name"]] = {"reachable": False, "mysql": "", "bootstrap": "", "mysqld": ""}
            else:
                states[node["name"]] = {"reachable": True, "mysql": m.group(1),
                                        "bootstrap": m.group(2), "mysqld": m.group(3)}
        return states

    def phase_galera(self):
        nodes = {n["name"]: n for n in self.cfg["galera_nodes"]}
        states = self.galera_states()
        verdict = galera_assess(states)
        if verdict == "starting":
            self.note("Galera: a node is mid-start (joining/SST); waiting.")
            return WAIT
        if verdict == "primary":
            self.state.pop("galera_down_since", None)
            self.since("galera_primary_since")
            return self._galera_complete(nodes, states)
        # -- no primary component anywhere --------------------------------
        self.state.pop("galera_primary_since", None)
        reachable = [n for n, s in states.items() if s["reachable"]]
        down_for = self.since("galera_down_since")
        if not reachable:
            self.note("Galera: no node reachable yet (waiting on their VMs/hypervisor).")
            return PROBLEM
        timeout = self.cfg.get("galera_wait_for_all_seconds", 900)
        missing = sorted(set(nodes) - set(reachable))
        if missing and down_for < timeout:
            self.note(f"Galera: cluster is down; waiting up to {timeout // 60} min for "
                      f"{', '.join(missing)} before bootstrapping without it.")
            return WAIT
        # Split-brain guard: "unreachable over SSH" must also mean "not
        # serving Galera". If a missing node still answers on its group-comm
        # or SQL port, a primary may well be running there, and bootstrapping
        # here would start a second, diverging cluster.
        alive = [n for n in missing
                 if any(self.ops.tcp_open(nodes[n]["address"], p) for p in (4567, 3306))]
        if alive:
            self.note(f"Galera: {', '.join(alive)} unreachable over SSH but still answering on its "
                      "Galera/SQL port -- not bootstrapping, that could split the cluster. Needs a look.")
            return PROBLEM
        return self._galera_full_recovery(nodes, states, reachable)

    def _galera_complete(self, nodes, states):
        """A primary exists: start stragglers one at a time, then move the
        bootstrap node back onto the normal unit."""
        for name in sorted(nodes):
            s = states[name]
            if not s["reachable"] or _up(s):
                continue
            last = self.state.get(f"galera_start:{name}", 0)
            if self.ops.now() - last < 300:
                self.note(f"Galera: {name} didn't rejoin on the last attempt; retrying shortly.")
                return WAIT
            if not self.dry_run:
                self.state[f"galera_start:{name}"] = self.ops.now()
            ok, out = self.act(f"start mysql on {name} (rejoin the running cluster)",
                               lambda name=name: self.ops.ssh(nodes[name]["address"], "sudo systemctl start mysql", timeout=3600))
            if ok:
                self.state.pop(f"galera_start:{name}", None)
            return PROGRESS
        unreachable = sorted(n for n, s in states.items() if not s["reachable"])
        boot = [n for n, s in states.items() if s["reachable"] and s["bootstrap"] == "active"]
        if boot and not unreachable and all(s["mysql"] == "active" for n, s in states.items() if n not in boot):
            name = boot[0]
            self.act(f"move {name} off mysql@bootstrap onto the normal mysql unit (the other nodes hold quorum)",
                     lambda: self.ops.ssh(nodes[name]["address"],
                                          "sudo systemctl stop mysql@bootstrap && sudo systemctl start mysql",
                                          timeout=3600))
            return PROGRESS
        if unreachable:
            self.note(f"Galera is up but degraded: {', '.join(unreachable)} unreachable.")
        return OK

    def _galera_full_recovery(self, nodes, states, reachable):
        positions = {n: None for n in nodes}
        for name in sorted(reachable):
            addr = nodes[name]["address"]
            if states[name]["mysqld"] == "yes":
                # mysqld running without an active unit: a wedged start.
                self.act(f"stop the stuck mysqld on {name}",
                         lambda addr=addr: self.ops.ssh(addr, "sudo systemctl stop mysql mysql@bootstrap", timeout=300))
            if self.dry_run:
                self.planned.append(f"run mysqld --wsrep-recover on {name}")
                ok, out = self.ops.ssh(addr, "sudo grep -E '^(uuid|seqno):' /var/lib/mysql/grastate.dat", timeout=30)
            else:
                ok, out = self.ops.ssh(addr, self.RECOVER_CMD, timeout=600)
            positions[name] = parse_position(out) if ok else None
        preferred = next((n for n, v in nodes.items() if v.get("bootstrap")), None)
        chosen, reason = choose_bootstrap(positions, preferred)
        if not chosen:
            if self.dry_run:
                chosen, reason = preferred, "dry-run: positions come from --wsrep-recover, not run"
            else:
                self.note(f"Galera: can't bootstrap -- {reason}. Needs a look: "
                          "docs/disaster-recovery.md Scenario C step 3.")
                return PROBLEM
        self._event(f"Galera full-cluster recovery: bootstrapping {chosen}: {reason}")
        ok, out = self.act(
            f"bootstrap Galera from {chosen}",
            lambda: self.ops.ssh(nodes[chosen]["address"],
                                 "sudo sed -i 's/^safe_to_bootstrap: 0/safe_to_bootstrap: 1/' /var/lib/mysql/grastate.dat"
                                 " && sudo systemctl start mysql@bootstrap", timeout=1800))
        if not ok:
            self.note(f"Galera: bootstrapping {chosen} failed: {out[-200:]}")
            return PROBLEM
        # The rest rejoin through _galera_complete on the next pass, one at
        # a time, and the bootstrap node moves back to `mysql` after that.
        self.note(f"Galera bootstrapped from {chosen} ({reason}); the other nodes rejoin next.")
        return PROGRESS

    # ---- phase 4 ---------------------------------------------------------
    def phase_datagateway(self, galera_ok):
        url = self.cfg["datagateway_probe_url"]
        status, _ = self.ops.http("GET", url, timeout=8)
        if 200 <= status < 300:
            for k in ("dg_fail_since", "dg_kicked_at", "proxysql_restarted_at"):
                self.state.pop(k, None)
            return OK
        if not galera_ok:
            self.note("DataGateway is down; waiting for Galera first.")
            return WAIT
        if self.since("galera_primary_since") < 120:
            self.note("DataGateway is down; giving it 2 minutes after Galera came back.")
            return WAIT
        now = self.ops.now()
        if "dg_kicked_at" not in self.state:
            ok, _ = self.act("restart the DataGateway pods (skip their CrashLoopBackOff wait)",
                             lambda: self.ops.ssh(self.cfg["kube_host"],
                                                  f"sudo kubectl delete pod -l {self.cfg['datagateway_selector']} --wait=false",
                                                  timeout=60))
            if ok and not self.dry_run:
                self.state["dg_kicked_at"] = now
            return PROGRESS
        if now - self.state["dg_kicked_at"] < 300:
            self.note("DataGateway pods restarted; waiting for them to come up.")
            return WAIT
        if "proxysql_restarted_at" not in self.state:
            ok, _ = self.act("restart proxysql (DataGateway still failing 5 min after its pods restarted)",
                             lambda: self.ops.ssh(self.cfg["proxysql_host"], "sudo systemctl restart proxysql", timeout=120))
            if ok and not self.dry_run:
                self.state["proxysql_restarted_at"] = now
            return PROGRESS
        if now - self.state["proxysql_restarted_at"] < 300:
            self.note("proxysql restarted; waiting for DataGateway.")
            return WAIT
        self.note(f"DataGateway ({url}) still failing after its pods and proxysql were restarted. "
                  "Out of automatic fixes -- needs a look (kubectl logs on kube-c-00).")
        return PROBLEM

    # ---- phase 5 ---------------------------------------------------------
    def phase_vault(self):
        status, body = self.ops.http("GET", f"{self.cfg['vault_url']}/v1/sys/seal-status", timeout=8)
        if status != 200 or not isinstance(body, dict):
            self.note(f"Vault isn't answering ({self.cfg['vault_url']}): {str(body)[:120]}")
            return PROBLEM
        if body.get("sealed"):
            return VAULT_SEALED
        for unit in self.cfg.get("vault_dependent_units", []):
            ok, out = self.ops.local(["systemctl", "is-failed", unit])
            if out.strip() == "failed":
                self.act(f"re-run {unit} (failed while Vault was unavailable)",
                         lambda unit=unit: self.ops.local(
                             ["sh", "-c", f"systemctl reset-failed {unit} && systemctl start --no-block {unit}"]))
        return OK

    # ---- phase 6 ---------------------------------------------------------
    def sweep(self):
        issues = []
        base = self.cfg["prometheus_url"]
        for query, what in (('up == 0', "scrape target down"),
                            ('probe_success{job!~"' + self.cfg.get("sweep_ignore_jobs", "blackbox_cameras") + '"} == 0',
                             "probe failing")):
            status, body = self.ops.http("GET", f"{base}/api/v1/query?query={urllib.parse.quote(query)}", timeout=10)
            if status != 200 or not isinstance(body, dict):
                issues.append(f"Prometheus query failed ({query}): {str(body)[:100]}")
                continue
            for r in body.get("data", {}).get("result", []):
                m = r.get("metric", {})
                issues.append(f"{what}: {m.get('instance', '?')} (job {m.get('job', '?')})")
        return issues

    # ---- ticket + silence ------------------------------------------------
    def _zammad_env(self):
        env = {}
        try:
            with open(self.cfg["zammad_env_file"]) as f:
                for line in f:
                    if "=" in line and not line.lstrip().startswith("#"):
                        k, v = line.rstrip("\n").split("=", 1)
                        env[k.strip()] = v.strip()
        except OSError:
            pass
        return env

    def _zammad(self, method, path, data):
        env = self._zammad_env()
        if not env.get("ZAMMAD_URL") or not env.get("ZAMMAD_API_TOKEN"):
            return 0, "no zammad credentials"
        return self.ops.http(method, env["ZAMMAD_URL"].rstrip("/") + path, data,
                             {"Authorization": f"Token token={env['ZAMMAD_API_TOKEN']}",
                              "Accept": "application/json"}, timeout=15)

    def post(self, subject, body, close=False):
        """Queue a ticket update; flush() delivers it (Zammad may be down)."""
        if self.dry_run or self.only:
            return
        self.state.setdefault("outbox", []).append({"subject": subject, "body": body, "close": close})

    def flush(self):
        outbox = self.state.get("outbox", [])
        while outbox:
            item = outbox[0]
            body = f"{BANNER}\n\n{item['body']}"
            if not self.state.get("ticket_id"):
                env = self._zammad_env()
                status, t = self._zammad("POST", "/api/v1/tickets", {
                    "title": f"[fleet-recovery] Recovery run {utcnow_iso(self.state['run_started_at'])}",
                    "group": env.get("ZAMMAD_GROUP", "Users"),
                    "customer": env.get("ZAMMAD_CUSTOMER_EMAIL", "zammad-admin@levantine.io"),
                    "article": {"subject": item["subject"], "body": body, "type": "note", "internal": False},
                })
                if status not in (200, 201) or not isinstance(t, dict):
                    return  # Zammad not up yet -- keep the outbox, retry next pass
                self.state["ticket_id"] = t["id"]
                self.log(f"Opened Zammad ticket {t.get('number')}")
                if item["close"]:
                    self._zammad("PUT", f"/api/v1/tickets/{t['id']}", {"state": "closed"})
            else:
                data = {"article": {"subject": item["subject"], "body": body, "type": "note", "internal": False}}
                if item["close"]:
                    data["state"] = "closed"
                status, _ = self._zammad("PUT", f"/api/v1/tickets/{self.state['ticket_id']}", data)
                if status not in (200, 201):
                    return
            outbox.pop(0)

    def silence(self):
        if self.dry_run or self.only or self.state.get("silence_id") or self.state.get("silence_done"):
            return
        now = self.ops.now()
        minutes = self.cfg.get("silence_minutes", 45)
        status, body = self.ops.http("POST", f"{self.cfg['alertmanager_url']}/api/v2/silences", {
            "matchers": [{"name": "alertname", "value": ".+", "isRegex": True, "isEqual": True}],
            "startsAt": datetime.fromtimestamp(now, timezone.utc).isoformat(),
            # Fixed, never extended: a crashed run must not mute alerting.
            "endsAt": datetime.fromtimestamp(now + minutes * 60, timezone.utc).isoformat(),
            "createdBy": "fleet-recovery",
            "comment": "Fleet recovery in progress -- see the [fleet-recovery] Zammad ticket. "
                       "Lifted as soon as everything not waiting on Vault is healthy.",
        })
        if status == 200 and isinstance(body, dict) and body.get("silenceID"):
            self.state["silence_id"] = body["silenceID"]
            self._event(f"Silenced alerts for up to {minutes} min (Alertmanager silence {body['silenceID']})")

    def unsilence(self):
        sid = self.state.get("silence_id")
        if not sid or self.dry_run:
            return
        status, _ = self.ops.http("DELETE", f"{self.cfg['alertmanager_url']}/api/v2/silence/{sid}")
        if status in (200, 404):
            self.state.pop("silence_id", None)
            self.state["silence_done"] = True
            self._event("Lifted the alert silence: normal alerting resumes for anything still wrong.")

    # ---- driving ---------------------------------------------------------
    PHASES = ("preconditions", "hypervisors", "nginx", "galera", "datagateway", "vault")

    def pass_once(self):
        """One pass over the phases. Returns {phase: status}."""
        self.notes = []
        results = {}
        want = (self.only,) if self.only else self.PHASES
        if "preconditions" in want:
            results["preconditions"] = self.phase_preconditions()
            if results["preconditions"] == WAIT and not self.only:
                return results  # nothing else works without internal DNS
        if "hypervisors" in want:
            results["hypervisors"] = self.phase_hypervisors()
        if "nginx" in want:
            results["nginx"] = self.phase_nginx()
        if "galera" in want:
            results["galera"] = self.phase_galera()
        if "datagateway" in want:
            galera_ok = results.get("galera", OK) == OK if not self.only else galera_assess(self.galera_states()) == "primary"
            results["datagateway"] = self.phase_datagateway(galera_ok)
        if "vault" in want:
            results["vault"] = self.phase_vault()
        return results

    def run(self):
        if os.path.exists(DISABLED_FLAG) and not self.dry_run:
            self.log(f"{DISABLED_FLAG} exists -- fleet-recovery is switched off. Doing nothing.")
            return 0
        fresh = not self.state.get("run_started_at")
        if fresh:
            self.state = {"run_started_at": self.ops.now()}
        first = True
        while True:
            results = self.pass_once()
            non_vault = {p: r for p, r in results.items() if p != "vault"}
            all_ok = all(r == OK for r in results.values())
            if self.dry_run:
                self.log(f"[dry-run] phase results: {results}")
                self.log(f"[dry-run] {len(self.planned)} action(s) planned" +
                         ("" if not self.planned else ": " + "; ".join(self.planned)))
                return 0
            if self.only:
                if all_ok or self.once:
                    self.log(f"{self.only}: {results[self.only]}")
                    return 0 if all_ok else 1
                self.ops.sleep(LOOP_SECONDS)
                continue
            if first and fresh and all_ok:
                self.log("Fleet healthy -- nothing to do.")
                self._clear_state()
                return 0
            if first and fresh:
                self._event(f"Recovery started: {results}")
                self.silence()
                self.post("Recovery started", self._status_body(results, "Found things to fix after a restart."))
                self.state["last_signature"] = self._signature(results)
            else:
                self._report_changes(results)
            self._notify_vault(results)
            first = False
            if all(r == OK for r in non_vault.values()):
                self.unsilence()
            if all_ok:
                self._finish()
                # Zammad lives on this host and may still be coming up: don't
                # drop the record just because the fleet beat it back.
                self.flush()
                for _ in range(60):
                    if not self.state.get("outbox"):
                        break
                    self._save_state()
                    self.ops.sleep(LOOP_SECONDS)
                    self.flush()
                if self.state.get("outbox"):
                    self.log(f"Zammad unreachable; {len(self.state['outbox'])} ticket update(s) not delivered.")
                self._save_state()
                self._clear_state(archive=True)
                return 0
            self.flush()
            self._save_state()
            self.ops.sleep(LOOP_SECONDS)

    def _signature(self, results):
        # Digits masked: notes carry "for N min" counters that would otherwise
        # make every pass look like news.
        return re.sub(r"\d+", "#", json.dumps([results, self.notes], sort_keys=True))

    def _report_changes(self, results):
        """Post to the ticket only when the picture changes, not every 30s."""
        sig = self._signature(results)
        if sig == self.state.get("last_signature"):
            return
        self.state["last_signature"] = sig
        if self.notes or any(r in (PROGRESS, PROBLEM) for r in results.values()):
            self.post("Recovery progress", self._status_body(results))

    def _notify_vault(self, results):
        """The one thing that needs the user: say so exactly once, as soon as
        everything else that can come back without Vault has."""
        if results.get("vault") != VAULT_SEALED or self.state.get("vault_wait_notified"):
            return
        others = {p: r for p, r in results.items() if p != "vault" and r != OK}
        if others and self.since("vault_sealed_seen") < 600:
            return  # give the rest a few minutes first, so the message is accurate
        self.state["vault_wait_notified"] = True
        self.post("Waiting for you: unseal Vault",
                  "Vault is **sealed**. " + UNSEAL_HELP + "\n\n" +
                  ("Everything else that doesn't need Vault is already back." if not others
                   else f"Still working on the rest meanwhile: {others}"))

    def _status_body(self, results, intro=""):
        lines = [intro] if intro else []
        lines.append("| Phase | State |\n|---|---|")
        lines += [f"| {p} | {r} |" for p, r in results.items()]
        if self.notes:
            lines.append("\n" + "\n".join(f"- {n}" for n in self.notes))
        return "\n".join(lines)

    def _finish(self):
        settle = self.cfg.get("settle_seconds", 600)
        deadline = self.ops.now() + settle
        issues = self.sweep()
        while issues and self.ops.now() < deadline:
            self.ops.sleep(60)
            issues = self.sweep()
        self.unsilence()
        timeline = "\n".join(f"- {utcnow_iso(ts)} {msg}" for ts, msg in self.state.get("timeline", []))
        took = int((self.ops.now() - self.state["run_started_at"]) // 60)
        if issues:
            self._event(f"Recovery done; {len(issues)} issue(s) left to normal alerting")
            self.post("Recovery finished with leftovers",
                      f"Recovery phases all done after {took} min, but these were still unhealthy "
                      f"{settle // 60} min later and are left to normal alerting / the incident agent:\n\n" +
                      "\n".join(f"- {i}" for i in issues) + f"\n\n**Timeline**\n{timeline}")
        else:
            self._event("Recovery complete; fleet healthy")
            self.post("Recovery complete",
                      f"Everything is back and Prometheus is clean ({took} min).\n\n**Timeline**\n{timeline}",
                      close=True)

    def _clear_state(self, archive=False):
        if self.dry_run or self.only:
            return
        if archive:
            try:
                os.replace(self.state_path, os.path.join(os.path.dirname(self.state_path), "last-run.json"))
            except OSError:
                pass
        else:
            try:
                os.remove(self.state_path)
            except OSError:
                pass


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="one pass, print planned actions, change nothing")
    ap.add_argument("--only", choices=Recovery.PHASES, help="run a single phase by hand (no ticket/silence)")
    ap.add_argument("--once", action="store_true", help="with --only: a single pass instead of looping until OK")
    ap.add_argument("--config", default=CONFIG_PATH)
    args = ap.parse_args(argv)
    with open(args.config) as f:
        cfg = json.load(f)
    ops = Ops(cfg["ssh_user"], cfg["ssh_key"])
    rec = Recovery(cfg, ops, cfg.get("state_file", "/var/lib/fleet-recovery/state.json"),
                   dry_run=args.dry_run, only=args.only, once=args.once,
                   log=lambda m: print(m, flush=True))
    return rec.run()


if __name__ == "__main__":
    sys.exit(main())
