#!/usr/bin/env python3
"""fleet-recovery: bring the fleet back by itself after an outage.

Runs on `service` at boot and every 15 minutes (systemd timer). On a healthy
fleet one pass finds nothing to do and it exits within seconds, silently.
Otherwise it loops every 30s doing only what doesn't recover on its own --
docs/disaster-recovery.md Scenario C, automated:

  0. preconditions   internal DNS answering; service's home-LAN IP held
  1. hypervisors     onboot VMs Proxmox didn't start; Wake-on-LAN a host
                     that doesn't answer
  2. nginx           on service (normally a no-op since the DNS-wait drop-in)
  3. galera          full-cluster crash recovery: --wsrep-recover on every
                     node, bootstrap from the most advanced, rejoin the rest
  4. datagateway     kick its pods (then proxysql) once Galera is back
  5. vault           sealed -> say so in the ticket and wait, forever; once
                     unsealed, re-run the Vault-dependent jobs that failed
  6. final sweep     Prometheus up==0 / probe_success==0, then close the ticket

Nothing here needs Vault: SSH with the automation key, the Zammad token
zammad-relay already keeps on disk, and Prometheus/Alertmanager on localhost.
Decisions (user, 2026-11-11): Vault stays manually unsealed; Galera recovery
is automatic and prefers availability over waiting (no sensitive or
revenue-bearing data, loss acceptable); reporting is a Zammad ticket.

Stdlib only. Every side effect goes through Ops, so tests swap in a fake.

Usage:
  fleet-recover                 normal run (what the systemd unit does)
  fleet-recover --dry-run       one pass, print what it would do, change nothing
  fleet-recover --only galera   just one phase, by hand, no ticket/silence
Off switch: touch /etc/fleet-recovery/disabled
"""
